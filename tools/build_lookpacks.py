def find_edge():
    for p in EDGE:
        if p.exists():
            return str(p)
    sys.exit("Microsoft Edge not found; it's needed to render the art.")


def render(html: str, width: int, height: int, workdir: Path) -> Image.Image:
    page = workdir / "page.html"
    shot = workdir / "shot.png"
    page.write_text(html, encoding="utf-8")
    if shot.exists():
        shot.unlink()
    subprocess.run([find_edge(), "--headless=new", "--disable-gpu", "--hide-scrollbars", "--force-device-scale-factor=1",
                    "--default-background-color=00000000", f"--window-size={width},{height}",
                    f"--screenshot={shot}", page.as_uri()], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=120)
    return Image.open(shot).convert("RGBA")


def svg_sheet(items, workdir):
    """items: [(key, svg_path, size)] -> {key: Image}. Packs everything into one page in rows."""
    x = y = row_h = 0
    width = 2048
    placed = []
    for key, path, size in items:
        if x + size > width:
            x, y, row_h = 0, y + row_h + 2, 0
        placed.append((key, path, size, x, y))
        x += size + 2
        row_h = max(row_h, size)
    height = y + row_h + 2
    imgs = "".join(f'<img src="{Path(p).as_uri()}" style="position:absolute;left:{px}px;top:{py}px;width:{s}px;height:{s}px">'
                   for _, p, s, px, py in placed)
    sheet = render(f'<html><body style="margin:0;background:transparent">{imgs}</body></html>', width, height, workdir)
    return {k: sheet.crop((px, py, px + s, py + s)) for k, _, s, px, py in placed}


def trail_sheet(workdir):
    """Draw every trail variant with trail-art.js into SPRITE-sized cells. Returns {(trail, n): Image}."""
    cells, js = [], []
    for ti, (tid, _, _, kind, variants, _) in enumerate(TRAILS):
        for vi, (c, c2) in enumerate(variants):
            x, y = vi * SPRITE, ti * SPRITE
            cells.append((tid, vi, x, y))
            fill = KIND_FILL[kind]
            if fill is None:   # the paw draws at a fixed r=7 (about 14px), so scale the canvas instead
                js.append(f"cx.save();cx.translate({x + SPRITE / 2},{y + SPRITE / 2});cx.scale({SPRITE / 16},{SPRITE / 16});"
                          f"D.paw({{x:0,y:0,rot:0}});cx.restore();")
            else:
                r = SPRITE / 2 / fill * 0.92
                c2s = f"'{c2}'" if c2 else "undefined"
                js.append(f"D.{kind}({{x:{x + SPRITE / 2},y:{y + SPRITE / 2},r:{r:.2f},rot:0,c:'{c}',c2:{c2s},t:4.49,life:1}});")
    w = max(len(v) for *_, v, _ in TRAILS) * SPRITE
    h = len(TRAILS) * SPRITE
    art = (DESIGN / "trail-art.js").as_uri()
    html = (f'<html><body style="margin:0;background:transparent"><canvas id="c" width="{w}" height="{h}"></canvas>'
            f'<script src="{art}"></script><script>const cx=document.getElementById("c").getContext("2d");'
            f'const D=TrailArt.make(cx);{"".join(js)}</script></body></html>')
    sheet = render(html, w, h, workdir)
    return {(t, v): sheet.crop((x, y, x + SPRITE, y + SPRITE)) for t, v, x, y in cells}


def dib(img: Image.Image) -> bytes:
    """32-bit BMP-style entry (BITMAPINFOHEADER + bottom-up BGRA + empty AND mask), as used inside .ico/.cur."""
    w, h = img.size
    header = struct.pack("<IiiHHIIiiII", 40, w, h * 2, 1, 32, 0, 0, 0, 0, 0, 0)
    rows = []
    for yy in range(h - 1, -1, -1):
        row = bytearray()
        for xx in range(w):
            r, g, b, a = img.getpixel((xx, yy))
            row += bytes((b, g, r, a))
        rows.append(bytes(row))
    mask_row = ((w + 31) // 32) * 4
    return header + b"".join(rows) + b"\0" * (mask_row * h)


def write_icon_file(path: Path, images, cursor_hotspot=None):
    """images: [Image]. cursor_hotspot: (x, y) in a 32px box -> writes a .cur (type 2) instead of an .ico."""
    is_cur = cursor_hotspot is not None
    entries, blobs = [], []
    for img in images:
        w, h = img.size
        if w >= 256:
            buf = BytesIO(); img.save(buf, "PNG"); data = buf.getvalue()   # PNG entries are standard for 256px
        else:
            data = dib(img)
        if is_cur:
            hx, hy = (round(cursor_hotspot[0] * w / 32), round(cursor_hotspot[1] * h / 32))
            fields = (hx, hy)
        else:
            fields = (1, 32)   # planes, bit count
        entries.append((w % 256, h % 256, fields, len(data)))
        blobs.append(data)
    offset = 6 + 16 * len(images)
    out = bytearray(struct.pack("<HHH", 0, 2 if is_cur else 1, len(images)))
    for (w, h, (f1, f2), size), blob in zip(entries, blobs):
        out += struct.pack("<BBBBHHII", w, h, 0, 0, f1, f2, size, offset)
        offset += size
    for blob in blobs:
        out += blob
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(out)


def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    (OUT / "previews").mkdir(parents=True)
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        items = []
        for sid, _, arrow, _, hand, _ in CURSOR_SETS:
            for part, svg in (("arrow", arrow), ("hand", hand)):
                for s in CURSOR_SIZES:
                    items.append((f"cur/{sid}/{part}/{s}", ASSETS / f"{svg}.svg", s))
        for fid, _ in FOLDERS:
            for s in ICON_SIZES:
                items.append((f"ico/{fid}/{s}", ASSETS / f"folder-{fid}.svg", s))
        rendered = svg_sheet(items, work)
        sprites = trail_sheet(work)
        walls = {}
        for p in THEME_PACKS:
            src = DESIGN / "wallpapers" / f"{p['id']}.svg"
            w, h = WALLPAPER_SIZE
            walls[p["id"]] = render(f'<html><body style="margin:0"><img src="{src.as_uri()}" style="display:block;width:{w}px;height:{h}px"></body></html>',
                                    w, h, work).convert("RGB")

    catalogue = {"cursor_sets": [], "folder_icons": [], "trails": [], "theme_packs": []}
    for sid, name, _, ahs, _, hhs in CURSOR_SETS:
        for part, hs in (("arrow", ahs), ("hand", hhs)):
            write_icon_file(OUT / "cursors" / sid / f"{part}.cur", [rendered[f"cur/{sid}/{part}/{s}"] for s in CURSOR_SIZES], hs)
            rendered[f"cur/{sid}/{part}/48"].save(OUT / "previews" / f"cursor-{sid}-{part}.png")
        catalogue["cursor_sets"].append({"id": sid, "name": name, "arrow": f"cursors/{sid}/arrow.cur", "hand": f"cursors/{sid}/hand.cur",
                                         "preview_arrow": f"previews/cursor-{sid}-arrow.png", "preview_hand": f"previews/cursor-{sid}-hand.png"})
    for fid, name in FOLDERS:
        write_icon_file(OUT / "folders" / f"{fid}.ico", [rendered[f"ico/{fid}/{s}"] for s in ICON_SIZES])
        rendered[f"ico/{fid}/64"].save(OUT / "previews" / f"folder-{fid}.png")
        catalogue["folder_icons"].append({"id": fid, "name": name, "icon": f"folders/{fid}.ico", "preview": f"previews/folder-{fid}.png"})
    for tid, name, tag, kind, variants, motion in TRAILS:
        files = []
        for vi in range(len(variants)):
            f = f"trails/{tid}_{vi}.png"
            (OUT / "trails").mkdir(exist_ok=True)
            sprites[(tid, vi)].save(OUT / f)
            files.append(f)
        sprites[(tid, 0)].resize((48, 48), Image.LANCZOS).save(OUT / "previews" / f"trail-{tid}.png")
        catalogue["trails"].append({"id": tid, "name": name, "tag": tag, "sprites": files, "preview": f"previews/trail-{tid}.png", **motion})

    (OUT / "wallpapers").mkdir(exist_ok=True)
    for p in THEME_PACKS:
        wall = walls[p["id"]]
        wall.save(OUT / "wallpapers" / f"{p['id']}.png", optimize=True)
        # the card: the wallpaper with its dock theme's preview sitting at the bottom, like on a real screen
        card = wall.resize((320, 180), Image.LANCZOS).convert("RGBA")
        dock_png = DOCK_PREVIEWS / f"{p['dock_theme']}.png"
        if dock_png.exists():
            dock = Image.open(dock_png).convert("RGBA")
            k = 150 / dock.width
            dock = dock.resize((150, max(1, round(dock.height * k))), Image.LANCZOS)
            card.alpha_composite(dock, ((320 - dock.width) // 2, 180 - dock.height - 2))
        card.convert("RGB").save(OUT / "previews" / f"pack-{p['id']}.png")
        catalogue["theme_packs"].append(dict(p, wallpaper=f"wallpapers/{p['id']}.png", preview=f"previews/pack-{p['id']}.png"))

    (OUT / "lookpacks.json").write_text(json.dumps(catalogue, indent=2), encoding="utf-8")
    n = sum(1 for _ in OUT.rglob("*") if _.is_file())
    print(f"wrote {n} files to {OUT}")


if __name__ == "__main__":
    main()
